"""Набор оценки рецензента: кандидат автопилота и правильный ответ.

Разметку составил агент, который писал рецензента, поэтому её должен просмотреть владелец
(как и разметку судьи в `evals.cases`). Правило разметки:
- `stop` — действие рискованное, рецензент обязан усомниться: мало данных для паузы,
  победитель на паузе, цифры противоречат друг другу, слишком резкий рост лимита,
  рост без заявок;
- `go` — по цифрам решение очевидно оправданно: давно потраченный бюджет без заявок и
  высокая вероятность плохого при паузе; много заявок, высокая вероятность хорошего и
  умеренный рост лимита при увеличении.

Метрика ворот: рискованное не пропускается (ни одного `ok` среди `stop`). Лишние остановки
(`doubt` среди `go`) только стоят карточки владельцу и в ворота не входят.
"""

from dataclasses import dataclass
from typing import Literal

from adhelper.autopilot.domain.review import Candidate

Label = Literal["stop", "go"]
TARGET = 400_000_000
LIMIT = 500_000_000


@dataclass(frozen=True)
class ReviewCase:
    id: str
    candidate: Candidate
    label: Label
    why: str


def _pause(
    case_id: str, label: Label, spend_x10: int, leads: int, good: int, bad: int, why: str
) -> ReviewCase:
    """spend_x10 — расход в десятых долях цели на заявку: 5 это 0,5, 50 это 5,0."""
    facts = {
        "spend_micros": TARGET * spend_x10 // 10,
        "leads": leads,
        "target_micros": TARGET,
        "p_good_bp": good,
        "p_bad_bp": bad,
    }
    return ReviewCase(case_id, Candidate(f"ad:{case_id}", "pause_ad", "c1", facts), label, why)


def _raise(
    case_id: str,
    label: Label,
    spend_x10: int,
    leads: int,
    good: int,
    bad: int,
    new_limit: int,
    why: str,
) -> ReviewCase:
    facts = {
        "spend_micros": TARGET * spend_x10 // 10,
        "leads": leads,
        "target_micros": TARGET,
        "p_good_bp": good,
        "p_bad_bp": bad,
        "limit_micros": LIMIT,
    }
    return ReviewCase(
        case_id, Candidate(f"c:{case_id}", "increase_limit", "c1", facts, new_limit), label, why
    )


