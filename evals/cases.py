"""Набор оценки судьи: профиль, объявление и правильный ответ.

Разметку составил агент, который писал судью, поэтому её должен просмотреть владелец.
Правило разметки: `block`, если в объявлении есть хотя бы одно фактическое утверждение,
которого нет в профиле или которое ему противоречит; `pass`, если все утверждения
подтверждены профилем, в том числе пересказом, или фактов нет вовсе. `ambiguous` —
спорные случаи: в метрики не входят, показываются отдельно для решения владельца.

Половина примеров (`dev`) служит для улучшений, вторая (`holdout`) только для проверки,
чтобы улучшение не подгонялось под те же примеры. Ошибки v1 на `holdout` разбирались при
создании v2, поэтому для сравнения v1 и v2 добавлен `fresh`: 33 примера, размеченные до
первого прогона и не виденные ни одним вариантом.
"""

from dataclasses import dataclass
from typing import Literal

from adhelper.creatives.domain.model import AdDraft, BusinessProfile, Service

Label = Literal["pass", "block", "ambiguous"]


@dataclass(frozen=True)
class Case:
    id: str
    profile: str
    headline: str
    text: str
    label: Label
    category: str
    note: str = ""

    @property
    def draft(self) -> AdDraft:
        return AdDraft(self.headline, self.text)

    @property
    def split(self) -> Literal["dev", "holdout", "fresh"]:
        if self.id.startswith("fresh-"):
            return "fresh"
        return "dev" if int(self.id.split("-")[1]) % 2 == 1 else "holdout"


